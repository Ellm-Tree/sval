# Generate chrome/browser/components/sval/SvalEmojiData.sys.mjs from Unicode's
# emoji-test.txt, the file Unicode publishes for keyboard palettes. It is in
# CLDR order, which is the order a picker should show.
#
# Usage: ./scripts/generate-emoji-data.py [path-or-url-to-emoji-test.txt]
#
# With no argument it fetches the latest published file. The output is
# committed, so building Sval never needs the network.
#
# What goes in: every fully-qualified emoji, grouped as Unicode groups them.
# A single-person skin-tone variant is folded into its base emoji's `tones`
# list (light to dark), so the picker shows one button and a tone control.
# Variants that mix two tones are left out.

import json
import re
import sys
import urllib.request
from pathlib import Path

SOURCE = "https://unicode.org/Public/emoji/latest/emoji-test.txt"
OUT = (
    Path(__file__).resolve().parent.parent
    / "chrome/browser/components/sval/SvalEmojiData.sys.mjs"
)

TONES = ["light", "medium-light", "medium", "medium-dark", "dark"]
TONE_NAME = re.compile(r"^(.*): (%s) skin tone$" % "|".join(TONES))
ENTRY = re.compile(r"^([0-9A-F ]+?)\s*;\s*([a-z-]+)\s*#\s*(\S+)\s+E[\d.]+\s+(.*)$")


# Emoji Sval keeps for its own marks, never offered for a workspace.
RESERVED = {"\U0001F916"}  # robot


def read(source):
    if re.match(r"^https?://", source):
        with urllib.request.urlopen(source, timeout=60) as response:
            return response.read().decode("utf-8")
    return Path(source).read_text(encoding="utf-8")


def main():
    text = read(sys.argv[1] if len(sys.argv) > 1 else SOURCE)
    version = re.search(r"^# Version: (\S+)", text, re.M).group(1)

    groups = []
    toned = {}  # base name -> {tone index: emoji}
    for line in text.splitlines():
        if line.startswith("# group: "):
            groups.append({"name": line[len("# group: "):], "emoji": []})
            continue
        entry = ENTRY.match(line)
        if not entry or entry.group(2) != "fully-qualified":
            continue
        char, name = entry.group(3), entry.group(4)
        if "skin tone" in name:
            tone = TONE_NAME.match(name)
            if tone:
                toned.setdefault(tone.group(1), {})[TONES.index(tone.group(2))] = char
            continue
        groups[-1]["emoji"].append([char, name])

    # "Component" holds the bare skin-tone swatches and hair pieces, which are
    # not emoji a person picks to name a place.
    groups = [g for g in groups if g["name"] != "Component"]

    # The robot face marks an agent's workspace (agent-control spec §6), so
    # no workspace of the user's may wear it. It has no skin tones, so no
    # variant needs dropping with it.
    for group in groups:
        group["emoji"] = [e for e in group["emoji"] if e[0] not in RESERVED]

    for group in groups:
        for item in group["emoji"]:
            variants = toned.get(item[1])
            if variants and len(variants) == len(TONES):
                item.append([variants[i] for i in range(len(TONES))])

    # The header below is the generated file's notice, not this script's.
    # REUSE-IgnoreStart
    lines = [
        "/* SPDX-License-Identifier: AGPL-3.0-only WITH AdditionRef-sval-app-store AND Unicode-3.0",
        " * Copyright 2026 Ellm Tree, Inc. */",
        # REUSE-IgnoreEnd
        "",
        "/**",
        " * The emoji the picker offers, generated by",
        " * `scripts/generate-emoji-data.py` from Unicode's emoji-test.txt, version",
        f" * {version}. Do not edit by hand.",
        " *",
        " * Emoji data is © Unicode, Inc. and used under the Unicode License v3,",
        " * LICENSES/Unicode-3.0.txt in Sval's repository.",
        " *",
        " * Each group is `{ name, emoji }`, in the order Unicode lists them. Each",
        " * emoji is `[character, name]`, or `[character, name, tones]` where `tones`",
        " * is its five skin-tone variants from light to dark.",
        " */",
        "",
        "// prettier-ignore",
        "export const EMOJI_GROUPS = [",
    ]
    for group in groups:
        lines.append("  {")
        lines.append(f"    name: {json.dumps(group['name'], ensure_ascii=False)},")
        lines.append("    emoji: [")
        for item in group["emoji"]:
            lines.append("      " + json.dumps(item, ensure_ascii=False) + ",")
        lines.append("    ],")
        lines.append("  },")
    lines.append("];")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")

    count = sum(len(g["emoji"]) for g in groups)
    print(f"{OUT.name}: {len(groups)} groups, {count} emoji, Unicode {version}")


main()
