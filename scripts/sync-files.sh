# Copy Sval's added files into the upstream checkout.
#
# Everything copied here is a new file, which is why it is not a patch: added
# files never conflict on the annual ESR rebase.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SRC="$REPO_ROOT/build/firefox"

if [[ ! -d "$SRC" ]]; then
  echo "error: no upstream checkout at $SRC — run scripts/fetch-upstream.sh first" >&2
  exit 1
fi

echo "==> Syncing branding"
# Neither MozillaBuild's msys2 nor Git for Windows ships rsync, so the
# destination is removed and copied afresh with cp -R, which also drops files
# a previous sync left.
mkdir -p "$SRC/browser/branding"
rm -rf "$SRC/browser/branding/sval"
mkdir -p "$SRC/browser/branding/sval"
cp -R "$REPO_ROOT/branding/sval/." "$SRC/browser/branding/sval/"

echo "==> Syncing chrome files"
# chrome/ mirrors the upstream tree layout, so a file at
# chrome/browser/base/content/sval-panel.js lands at that path in the tree.
# chrome/ files land at scattered paths across the upstream tree, so nothing is
# deleted by directory, as branding is. Instead the tree keeps a manifest of
# what the last sync copied, and a path in it that chrome/ lacks is
# removed. Without that, a deleted or renamed file stays in the tree and keeps
# being built, and a staged engine artifact that has since been removed keeps
# the stub below from being written.
MANIFEST="$SRC/.sval-synced-files"
copied="$(mktemp)"
( cd "$REPO_ROOT/chrome" && find . -type f ! -name '.gitkeep' -print ) |
while IFS= read -r rel; do
  rel="${rel#./}"
  dest="$SRC/$rel"
  mkdir -p "$(dirname "$dest")"
  cp "$REPO_ROOT/chrome/$rel" "$dest"
  echo "$rel" >> "$copied"
done
if [[ -f "$MANIFEST" ]]; then
  while IFS= read -r rel; do
    if ! grep -qxF -- "$rel" "$copied"; then
      echo "    removing $rel (no longer in chrome/)"
      rm -f "$SRC/$rel"
    fi
  done < "$MANIFEST"
fi
mv -f "$copied" "$MANIFEST"

# Sval's jar.mn lists the engine artifact unconditionally, so packaging needs
# both files to exist. They are generated by scripts/build-core-wasm.sh from
# engine/ and never committed, so a checkout that has not built the engine
# does not have them. A stand-in for whichever is absent lets the browser
# build and run, and the engine reports what is missing when anything loads
# it. Each file is written only when absent, so a real artifact is never
# touched.
SVAL_DIR="$SRC/browser/components/sval"
ENGINE_MISSING_MESSAGE="sval: the engine artifact is not built — run scripts/build-core-wasm.sh"

if [[ ! -f "$SVAL_DIR/sval_core.mjs" ]]; then
  echo "==> Stubbing sval_core.mjs (no engine artifact staged)"
  mkdir -p "$SVAL_DIR"
  cat > "$SVAL_DIR/sval_core.mjs" <<STUB
/* Generated by scripts/sync-files.sh when no engine artifact is staged. */

// An Error with a code, which is what the engine throws, so the worker's own
// error handling treats this identically to a real engine failure.
const MESSAGE = "$ENGINE_MISSING_MESSAGE";

function unavailable() {
  throw Object.assign(new Error(MESSAGE), { code: "engine_not_built" });
}

export class SvalDocument {
  constructor() {
    unavailable();
  }
  static loadJson() {
    unavailable();
  }
}

export class SyncOutcome {}

export function initSync() {
  unavailable();
}

export default function () {
  unavailable();
}
STUB
  # Every other name a worker imports from the glue becomes a function that
  # throws the same message, so the stub cannot fall behind the workers: a name
  # it lacked would fail a worker's module link before any message showed.
  imports=""
  for WORKER in "$REPO_ROOT"/chrome/browser/components/sval/*.worker.mjs; do
    names="$(sed -n '/^import initWasm, {$/,/^} from "chrome:\/\/browser\/content\/sval\/sval_core.mjs";$/p' "$WORKER" |
      sed -e '1d;$d' -e 's/^[[:space:]]*//' -e 's/,$//' -e 's/ as .*//')"
    if [[ -z "$names" ]]; then
      echo "error: could not read the engine imports from $WORKER" >&2
      exit 1
    fi
    imports+="$names"$'\n'
  done
  while IFS= read -r name; do
    [[ -z "$name" || "$name" == "SvalDocument" ]] && continue
    printf '\nexport function %s() {\n  unavailable();\n}\n' "$name" >> "$SVAL_DIR/sval_core.mjs"
  done < <(sort -u <<<"$imports")
fi

# wasm-bindgen's output follows nobody's lint rules. scripts/lint.sh never sees
# it, because the glue is gitignored, but a `mach lint` over the whole component
# directory does. Two passes keep that run on Sval's own files, both against the
# copy inside the disposable build tree and never against the staged artifact:
# a file-level eslint-disable for the rule violations, and prettier for the
# formatting, which eslint reports at line 0 where an inline directive cannot
# reach it.
# Excluding the file in one of Mozilla's own config files would cost a patch.
# The file keeps its .mjs name because the file channel takes the content type
# from the symlink's target, and a module needs that extension.
#
# The tree's own prettier is used, and only if it is there: before
# `mach bootstrap` has installed node_modules it is not, and the file is left
# as it is.
if [[ -f "$SVAL_DIR/sval_core.mjs" ]] &&
   ! head -n 1 "$SVAL_DIR/sval_core.mjs" | grep -q "eslint-disable"; then
  {
    echo "/* eslint-disable -- generated by wasm-bindgen; see scripts/sync-files.sh */"
    cat "$SVAL_DIR/sval_core.mjs"
  } > "$SVAL_DIR/sval_core.mjs.tmp"
  mv -f "$SVAL_DIR/sval_core.mjs.tmp" "$SVAL_DIR/sval_core.mjs"
fi
# Run from the checkout: prettier resolves `.prettierrc.js` and
# `.prettierignore` against the working directory, and the file must pass the
# tree's own check, whose settings differ from prettier's defaults.
if [[ -x "$SRC/node_modules/.bin/prettier" ]]; then
  ( cd "$SRC" && ./node_modules/.bin/prettier \
      --write browser/components/sval/sval_core.mjs > /dev/null )
fi

if [[ ! -f "$SVAL_DIR/sval_core_bg.wasm" ]]; then
  echo "==> Stubbing sval_core_bg.wasm (no engine artifact staged)"
  mkdir -p "$SVAL_DIR"
  # The eight bytes of an empty WASM module: the "\0asm" magic and version 1.
  # The stub glue throws before anything instantiates it, and it is a real
  # module so nothing that reads the bytes fails.
  printf '\000asm\001\000\000\000' > "$SVAL_DIR/sval_core_bg.wasm"
fi

echo "==> Sync complete"
