"""Write the phone's Public Suffix List, src/effective_tld_names.txt, from
Gecko's at the pinned Firefox commit, so a site ends where it ends on the
desktop (`nsEffectiveTLDService`).

    mobile/sval-mobile/generate-psl.py [<firefox checkout>]

The checkout defaults to the repository's build/firefox, and must hold the
commit upstream.txt pins. Each rule is normalized as Gecko's
netwerk/dns/prepare_tlds.py normalizes it before compiling the list: ASCII
labels lowercased, any other label through IDNA's ToASCII. The output is
committed, and run again when the pin moves.
"""

import encodings.idna
import pathlib
import re
import subprocess
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent.parent
OUT = pathlib.Path(__file__).resolve().parent / "src" / "effective_tld_names.txt"
SOURCE = "netwerk/dns/effective_tld_names.dat"


def pinned_ref():
    text = (REPO / "upstream.txt").read_text()
    return re.search(r"^UPSTREAM_REF=(\S+)$", text, re.MULTILINE).group(1)


def label(text):
    return text.lower() if text.isascii() else encodings.idna.ToASCII(text).decode("ascii")


def main():
    checkout = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else REPO / "build" / "firefox"
    ref = pinned_ref()
    dat = subprocess.run(
        ["git", "-C", str(checkout), "show", f"{ref}:{SOURCE}"],
        check=True, capture_output=True, text=True,
    ).stdout
    lines = dat.splitlines()
    rules = {}
    for line in lines:
        line = line.rstrip()
        if line.startswith("//") or not line.strip():
            continue
        line = re.split(r"[ \t\n]", line, maxsplit=1)[0]
        kind = 0
        if line.startswith("!"):
            kind, line = 1, line[1:]
        elif line.startswith("*."):
            kind, line = 2, line[2:]
        name = ".".join(map(label, line.split(".")))
        if name in rules:
            sys.exit(f"{name} is in the list twice")
        rules[name] = kind
    version = next((line for line in lines if line.startswith("// VERSION:")), "")
    header = [
        *lines[:3],
        "",
        f"// Generated by mobile/sval-mobile/generate-psl.py from Gecko's {SOURCE}",
        f"// at {ref}. {version[3:]}",
        "// One rule a line: the name, then 0 for a suffix, 1 for an exception, 2",
        "// for a wildcard over the names under it.",
    ]
    body = [f"{name}{kind}" for name, kind in sorted(rules.items())]
    OUT.write_text("\n".join(header + body) + "\n")
    print(f"{len(body)} rules written to {OUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
